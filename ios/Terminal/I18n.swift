    /// Both languages say the same things: a key in one and not in the other is a text nobody translated.
    static func missing() -> Set<String> { Set(es.keys).symmetricDifference(Set(en.keys)) }
}

/// `t("key", "n" to 3)`: the text in the active language, with its `{var}` filled.
func t(_ key: String, _ vars: (String, Any)...) -> String {
    let table = DotrinoLang.shared.code == "en" ? I18n.en : I18n.es
    guard var s = table[key] else { fatalError("missing i18n key: \(key)") }
    for (k, v) in vars { s = s.replacingOccurrences(of: "{\(k)}", with: "\(v)") }
    return s
}
